import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const fromWeb = createRequire(new URL('../package.json', import.meta.url));
const { chromium, expect: baseExpect } = fromWeb('@playwright/test');
const expect = baseExpect.configure({ timeout: 20000 });
const WebSocket = fromWeb('next/dist/compiled/ws');
const fixture = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const origin = 'http://localhost:3000';
const target = `http://localhost:${fixture.webPort}`;
const root = `/seller/${fixture.merchantId}/catalog`;
const evidence = { actualNextApiAndStorage: true, nativeFileObjects: true, loginFormTested: false, fixtureLocalNetworkPermission: true, writes: [], storageHttp: [], layouts: [], pageErrors: [], consoleErrors: [] };
const redact = value => String(value).replaceAll(fixture.token, '[redacted]').replace(/X-Amz-(Signature|Credential|Security-Token)=[^&\s]+/gi, 'X-Amz-$1=[redacted]');

(async () => {
  const deadline = Date.now() + 90000;
  let ready = false;
  while (!ready && Date.now() < deadline) {
    try { ready = (await fetch(target + '/login', { signal: AbortSignal.timeout(3000) })).ok; } catch { ready = false; }
    if (!ready) await new Promise(resolve => setTimeout(resolve, 500));
  }
  if (!ready) throw new Error('Isolated Next did not become ready');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  let page;
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'vi-VN', timezoneId: 'Asia/Ho_Chi_Minh' });
    await context.grantPermissions(['local-network-access'], { origin });
    await context.addCookies([{ name: 'covie_at', value: fixture.token, url: origin, httpOnly: true, sameSite: 'Lax' }]);
    await context.routeWebSocket('**/*', socket => {
      const url = new URL(socket.url());
      const upstream = new WebSocket(target.replace('http:', 'ws:') + url.pathname + url.search);
      const queued = [];
      socket.onMessage(message => { if (upstream.readyState === WebSocket.OPEN) upstream.send(message); else queued.push(message); });
      upstream.on('open', () => { for (const message of queued) upstream.send(message); });
      upstream.on('message', (message, binary) => socket.send(binary ? message : message.toString()));
      upstream.on('error', error => evidence.consoleErrors.push(redact(error.message)));
      upstream.on('close', () => socket.close());
      socket.onClose(() => upstream.close());
    });
    await context.route(origin + '/**', async route => {
      const request = route.request();
      const url = new URL(request.url());
      const response = await route.fetch({ url: target + url.pathname + url.search, headers: { ...await request.allHeaders(), host: 'localhost:3000' }, timeout: 60000 });
      if (url.pathname.includes('/catalog-items') && ['POST', 'PATCH'].includes(request.method())) evidence.writes.push({ method: request.method(), status: response.status(), body: request.postDataJSON() });
      return route.fulfill({ response }).catch(() => undefined);
    });
    page = await context.newPage();
    page.on('pageerror', error => evidence.pageErrors.push(redact(error.message)));
    page.on('console', message => { if (message.type() === 'error') evidence.consoleErrors.push(redact(message.text())); });
    page.on('response', response => { if (new URL(response.url()).origin === fixture.storageOrigin) evidence.storageHttp.push({ method: response.request().method(), status: response.status() }); });
    await page.goto(origin + root + '/new');
    await expect(page.getByRole('heading', { name: 'Tạo nội dung bán', exact: true })).toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Caption', exact: true })).toBeVisible();
    await page.getByRole('combobox', { name: 'Danh mục', exact: true }).click();
    await page.getByRole('option', { name: 'Gallery category', exact: true }).click();
    await page.getByRole('combobox', { name: 'Điểm bán', exact: true }).click();
    await page.getByRole('option', { name: /^Gallery counter/ }).click();
    await page.getByRole('textbox', { name: 'Tên', exact: true }).fill('Browser gallery item');
    await page.getByRole('textbox', { name: 'Mô tả', exact: true }).fill('Commercial baseline');
    await page.getByLabel('Giá chính xác (VND)', { exact: true }).fill('25000');
    const caption = '  <b>Literal caption</b>\nDòng hai  ';
    await page.getByRole('textbox', { name: 'Caption', exact: true }).fill(caption);
    await expect(page.getByLabel('Số ký tự caption')).toHaveText(`${caption.length} / 3000 UTF-16 units`);
    await page.getByLabel('Ảnh Social', { exact: true }).setInputFiles([path.join(fixture.output, 'first.png'), path.join(fixture.output, 'second.png')]);
    const gallery = page.locator('ol').filter({ has: page.getByRole('button', { name: 'Xóa first.png', exact: true }) });
    await expect(gallery.getByRole('listitem')).toHaveCount(2);
    await page.evaluate(() => { window.fixtureDragEvents = []; for (const type of ['dragstart', 'drop']) document.addEventListener(type, event => window.fixtureDragEvents.push({ type, trusted: event.isTrusted }), true); });
    await gallery.getByRole('listitem').nth(1).dragTo(gallery.getByRole('listitem').nth(0));
    await expect(gallery.getByRole('listitem').first()).toContainText('second.png · Ảnh bìa');
    evidence.dragEvents = await page.evaluate(() => window.fixtureDragEvents);
    expect(evidence.dragEvents.some(event => event.type === 'drop' && event.trusted)).toBe(true);
    const preview = page.getByRole('region', { name: 'Xem trước bài đăng Social', exact: true });
    await expect(preview.getByText('<b>Literal caption</b> Dòng hai', { exact: true })).toBeVisible();
    await expect(preview.locator('b')).toHaveCount(0);
    for (const width of [360, 768, 1280, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      evidence.layouts.push(await page.evaluate(() => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth })));
      await page.getByRole('textbox', { name: 'Caption', exact: true }).scrollIntoViewIfNeeded();
      await expect(page).toHaveURL(origin + root + '/new');
      await expect(page.getByText('Nội dung hiển thị trên Khám phá', { exact: true })).toBeVisible();
      await page.screenshot({ path: path.join(fixture.output, `caption-${width}.png`) });
      await preview.scrollIntoViewIfNeeded();
      await expect(preview.getByRole('heading', { name: 'Xem trước bài đăng Social', exact: true })).toBeVisible();
      await page.screenshot({ path: path.join(fixture.output, `preview-${width}.png`) });
    }
    const created = page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1/merchants/${fixture.merchantId}/catalog-items` && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Tạo nội dung', exact: true }).click();
    const createResponse = await created;
    expect(createResponse.status()).toBe(201);
    evidence.itemId = (await createResponse.json()).id;
    await expect(page).toHaveURL(origin + root);
    await page.goto(origin + root + '/' + evidence.itemId);
    await expect(page.getByRole('heading', { name: 'Thông tin chung', exact: true })).toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Caption', exact: true })).toHaveValue(caption.trim());
    const detailPath = `/api/v1/merchants/${fixture.merchantId}/catalog-items/${evidence.itemId}`;
    const read = () => page.evaluate(async route => { const response = await fetch(route, { credentials: 'include', cache: 'no-store' }); if (!response.ok) throw new Error(`Read ${response.status}`); return response.json(); }, detailPath);
    const initial = await read();
    expect(initial.description).toBe('Commercial baseline');
    expect(initial.media).toHaveLength(2);
    await page.getByLabel('Ảnh Social', { exact: true }).setInputFiles(path.join(fixture.output, 'third.png'));
    await page.getByRole('button', { name: 'Làm bìa third.png', exact: true }).focus();
    await page.keyboard.press('Enter');
    await page.getByRole('textbox', { name: 'Caption', exact: true }).fill('Edited caption\nDòng sau');
    const patched = page.waitForResponse(response => new URL(response.url()).pathname === detailPath && response.request().method() === 'PATCH');
    await page.getByRole('button', { name: 'Lưu thông tin', exact: true }).click();
    expect((await patched).status()).toBe(204);
    await expect(page.getByText('Caption chưa lưu.', { exact: true })).toHaveCount(0);
    await page.reload();
    await expect(page.getByRole('textbox', { name: 'Caption', exact: true })).toHaveValue('Edited caption\nDòng sau');
    const edited = await read();
    expect(edited.media).toHaveLength(3);
    expect(edited.media.slice(1).map(media => media.id)).toEqual(initial.media.map(media => media.id));
    expect(edited.media.map(media => media.sortOrder)).toEqual([0, 1, 2]);
    expect(edited.media[0].primary).toBe(true);
    expect(edited.variants).toEqual(initial.variants);
    expect(edited.locationOffers).toEqual(initial.locationOffers);
    expect(edited.description).toBe(initial.description);
    expect(edited.listingStatus).toBe(initial.listingStatus);
    await page.getByRole('button', { name: 'Xóa caption', exact: true }).click();
    const cleared = page.waitForResponse(response => new URL(response.url()).pathname === detailPath && response.request().method() === 'PATCH');
    await page.getByRole('button', { name: 'Lưu thông tin', exact: true }).click();
    expect((await cleared).status()).toBe(204);
    await expect(page.getByText('Caption chưa lưu.', { exact: true })).toHaveCount(0);
    await page.reload();
    await expect(page.getByRole('textbox', { name: 'Caption', exact: true })).toHaveValue('');
    const final = await read();
    expect(final.media).toEqual(edited.media);
    expect(final.locationOffers).toEqual(initial.locationOffers);
    expect(final.description).toBe('Commercial baseline');
    const images = page.locator('ol img');
    await expect(images).toHaveCount(3);
    await expect.poll(() => images.evaluateAll(elements => elements.every(image => image.complete && image.naturalWidth === 8))).toBe(true);
    expect(evidence.storageHttp.filter(event => event.method === 'PUT' && event.status === 200)).toHaveLength(3);
    evidence.browser = browser.version();
    evidence.functionalResult = 'PASS: real create/edit/clear, native drag and keyboard cover, direct storage PUT/complete/GET, reload keeps caption/order/commerce';
    fs.writeFileSync(path.join(fixture.output, 'evidence.json'), JSON.stringify(evidence, null, 2));
    for (const layout of evidence.layouts) expect(layout.documentWidth).toBeLessThanOrEqual(layout.width);
    evidence.result = 'PASS';
    fs.writeFileSync(path.join(fixture.output, 'evidence.json'), JSON.stringify(evidence, null, 2));
    console.log(redact(JSON.stringify(evidence)));
  } catch (error) {
    if (page) evidence.bodyAtFailure = await page.locator('body').innerText().catch(() => 'unavailable');
    console.log(redact(JSON.stringify(evidence)));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(redact(error.stack ?? error)); process.exitCode = 1; });
